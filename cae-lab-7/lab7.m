% Лабораторная 7

clc; clear; close all;

% Вектор-строка из 4 произвольных элементов
v = [3, -7, 12, 5];

% Вектор-столбец из 4 произвольных элементов
w = [2; 8; -1; 4];

% Произвольная матрица 4x4
m = [1 2 3 4; 5 6 7 8; -1 0 2 3; 4 -2 1 6];

disp('Вектор-строка v:'); disp(v)
disp('Вектор-столбец w:'); disp(w)
disp('Матрица m:'); disp(m)


Z = zeros(4,4);      % матрица с нулевыми элементами
O = ones(4,4);       % матрица с единичными элементами (все элементы = 1)
R = rand(4,4);       % матрица со случайными значениями (равномерное распределение [0,1])
I = eye(4,4);        % матрица с единичными диагональными элементами (единичная матрица)

disp('Нулевая матрица Z:'); disp(Z)
disp('Матрица единиц O:'); disp(O)
disp('Случайная матрица R:'); disp(R)
disp('Единичная матрица I:'); disp(I)


v_mean = mean(v);          % среднее значение
v_sum  = sum(v);           % сумма элементов
v_sorted = sort(v);        % сортировка по возрастанию

fprintf('Среднее значение v = %.4f\n', v_mean);
fprintf('Сумма элементов v = %.4f\n', v_sum);
disp('Отсортированный вектор v:'); disp(v_sorted)


m_max = max(m(:));   % максимальный элемент всей матрицы
m_min = min(m(:));   % минимальный элемент всей матрицы

fprintf('Максимальный элемент m = %d\n', m_max);
fprintf('Минимальный элемент m = %d\n', m_min);


m2 = [2 0 1 1; 1 3 0 2; 0 1 4 1; 2 2 1 3];   % вторая матрица для операций

C_add = m + m2;              % сложение
C_sub = m - m2;               % вычитание
C_mul = m * m2;                % умножение матриц (обычное, построчное)
C_div = m / m2;                 % деление матриц (эквивалентно m*inv(m2))
C_transpose = m';               % транспонирование

disp('Сложение m+m2:'); disp(C_add)
disp('Вычитание m-m2:'); disp(C_sub)
disp('Умножение m*m2:'); disp(C_mul)
disp('Деление m/m2:'); disp(C_div)
disp('Транспонированная m'':'); disp(C_transpose)


m_inv = inv(m);
disp('Обратная матрица m^-1:'); disp(m_inv)

% Проверка: m * m_inv должна дать единичную матрицу (с точностью до округления)
disp('Проверка m*m^-1 (должна быть ≈ единичная):'); disp(m * m_inv)


m_concat = [m, m2];    % горизонтальное объединение (соединение по столбцам)
disp('Горизонтальная конкатенация [m, m2]:'); disp(m_concat)
disp('Размер результата:'); disp(size(m_concat))    % должно быть 4x8


m_squared = m^2;      % именно матричное возведение в степень (m*m), а не поэлементное
disp('m в квадрате (матричное умножение m*m):'); disp(m_squared)

% Для сравнения - поэлементное возведение в квадрат (другая операция!):
m_squared_elem = m.^2;
disp('Поэлементный квадрат m.^2:'); disp(m_squared_elem)


[rows, cols] = size(m);
fprintf('Число строк: %d, число столбцов: %d\n', rows, cols);


col_max = max(m);          % вектор-строка максимумов каждого столбца
col_min = min(m);          % вектор-строка минимумов каждого столбца
m_sorted_cols = sort(m);   % сортировка КАЖДОГО столбца по отдельности (по возрастанию)
col_sum = sum(m);          % вектор-строка сумм по столбцам
col_prod = prod(m);        % вектор произведений элементов каждого столбца

disp('Максимумы по столбцам:'); disp(col_max)
disp('Минимумы по столбцам:'); disp(col_min)
disp('Матрица с отсортированными столбцами:'); disp(m_sorted_cols)
disp('Суммы по столбцам:'); disp(col_sum)
disp('Произведения по столбцам:'); disp(col_prod)


x = linspace(0.1, 5, 200);   % 0.1, а не 0, т.к. в f2/f3 участвует... 
                               % (для варианта 4 log нет, но x=0 всё равно 
                               % безопасная точка; берём диапазон для наглядности формы функций)

f1 = cos(x) + exp(x);
f2 = cos(x).^2 + x;
f3 = cos(x.^2) + abs(x);
f4 = exp(x) + x.^2;

figure;
plot(x, f1, 'r-',  'LineWidth', 1.5); hold on;
plot(x, f2, 'b--', 'LineWidth', 1.5);
plot(x, f3, 'g-.', 'LineWidth', 1.5);
plot(x, f4, 'k:',  'LineWidth', 1.5);
grid on;

xlabel('x');
ylabel('f(x)');
title('Графики функций f1..f4 — Вариант 4');
legend('f1 = cos(x)+e^x', 'f2 = cos^2(x)+x', 'f3 = cos(x^2)+|x|', 'f4 = e^x+x^2', 'Location', 'northwest');


figure;

subplot(2,2,1);
plot(x, f1, 'r-', 'LineWidth', 1.5);
grid on;
xlabel('x'); ylabel('f_1(x)');
title('f1 = cos(x) + e^x');

subplot(2,2,2);
plot(x, f2, 'b--', 'LineWidth', 1.5);
grid on;
xlabel('x'); ylabel('f_2(x)');
title('f2 = cos^2(x) + x');

subplot(2,2,3);
plot(x, f3, 'g-.', 'LineWidth', 1.5);
grid on;
xlabel('x'); ylabel('f_3(x)');
title('f3 = cos(x^2) + |x|');

subplot(2,2,4);
plot(x, f4, 'k:', 'LineWidth', 1.5);
grid on;
xlabel('x'); ylabel('f_4(x)');
title('f4 = e^x + x^2');

sgtitle('Графики функций варианта 4 в отдельных окнах (subplot)');